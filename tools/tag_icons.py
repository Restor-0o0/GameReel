import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'tools/tag_icons'
PRESENTATION = ROOT / 'app/shared/src/commonMain/kotlin/com/restor/gamereel/ui/presentation'
GRID = 4

STYLE = (
    'Square image, a strict 4x4 grid of 16 separate game-UI icons on a plain pure white background. '
    'Every icon sits centered in its own equal cell with generous white space between cells; '
    'nothing crosses cell borders. Each icon is a rounded-square app-style tile with a soft dark-teal '
    'gradient background and one bold, simple, instantly readable symbol in warm light colors '
    '(cream, amber, coral) with subtle shading. Same style, size and lighting for all 16 tiles. '
    'No text, no letters, no numbers, no captions, no grid lines, no frames around the grid.'
)


HINTS = dict(CORE='core gameplay', SECONDARY_MECHANIC='secondary mechanic', STRUCTURE='game structure',
    PRESSURE='pressure or challenge', CAMERA='camera view', VISUAL='visual style', SETTING='setting',
    TWIST='design twist', PROGRESSION='progression', MULTIPLAYER='player mode', INTERACTION='player interaction',
    SCOPE='production scope', MONETIZATION='business model', PLATFORM_TRAIT='platform trait', OTHER='genre tag',
    THEME='mood and theme', WORLD='world and era', LOCATION='location', ENVIRONMENT='natural environment')


def slug(name):
    return re.sub(r'[^a-z0-9]+', '_', name.lower()).strip('_')


def read_emoji():
    icons, category = {}, None
    for line in (DATA / 'emoji.txt').read_text(encoding='utf-8').splitlines():
        if line.startswith('## '):
            category = line[3:]
        elif line.strip():
            name, emoji = line.rsplit('|', 1)
            icons[f'{category}:{name}'] = emoji
    return icons


def write_kotlin():
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = [f'    {quote(key)} to {quote(emoji)},' for key, emoji in read_emoji().items()]
    header = 'package com.restor.gamereel.ui.presentation\n\n// generated by tools/tag_icons.py from tools/tag_icons/emoji.txt, dont edit\n'
    (PRESENTATION / 'TagIcons.kt').write_text(header + 'internal val tagIcons = mapOf(\n' + '\n'.join(lines) + '\n)\n', encoding='utf-8')


# dump: category, name, id, icon, count, sources (tab separated, one tag per line)
def write_sheets(dump):
    counts, labels, best = {}, {}, {}
    for row in Path(dump).read_text(encoding='utf-8').splitlines():
        category, name, _, _, count, _ = row.split('\t')
        key = slug(name)
        counts[key] = counts.get(key, 0) + int(count)
        if int(count) > best.get(key, -1):
            best[key] = int(count)
            labels[key] = f'{name.strip().lower()} ({HINTS[category]})'
    order = sorted(counts, key=lambda key: (-counts[key], key))
    sheets = [order[i:i + GRID * GRID] for i in range(0, len(order), GRID * GRID)]
    manifest = [{'sheet': index + 1, 'icons': [{'file': key, 'tag': labels[key]} for key in keys]}
                for index, keys in enumerate(sheets)]
    (DATA / 'sheets.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=1), encoding='utf-8')


def write_prompts():
    manifest = json.loads((DATA / 'sheets.json').read_text(encoding='utf-8'))
    total = sum(len(sheet['icons']) for sheet in manifest)
    out = [
        '# Иконки тегов',
        '',
        f'{total} тегов на {len(manifest)} листах по {GRID * GRID}. Листы идут от самых частых тегов к редким, '
        'так что можно остановиться где угодно: всё, что не нарисовано, останется на эмодзи.',
        '',
        'Как пользоваться:',
        '',
        '1. Скопируй блок промпта листа целиком в ChatGPT (генерация картинок), один лист за раз.',
        '2. Сохрани картинку как `tools/tag_icons/sheets/NNN.png`, где NNN — номер листа с нулями (`001.png`, `002.png`, …).',
        '3. Если какая-то иконка вышла неудачной, перегенерируй весь лист или попроси ChatGPT поправить конкретную клетку.',
        '4. Когда наберётся сколько хочешь листов, скажи Claude — он нарежет и подключит.',
        '',
        'Главное — чтобы на листе было ровно 16 иконок в сетке 4×4 и порядок совпадал со списком '
        '(слева направо, сверху вниз). Если ChatGPT нарисовал меньше или перепутал порядок — перегенерируй.',
        '',
    ]
    for sheet in manifest:
        number = f"{sheet['sheet']:03d}"
        items = '\n'.join(f"{index + 1}. {icon['tag']}" for index, icon in enumerate(sheet['icons']))
        out += [
            f'## Лист {number}',
            '',
            '```',
            STYLE + ('' if len(sheet['icons']) == GRID * GRID else
                     f" Only the first {len(sheet['icons'])} cells contain icons; leave the remaining cells empty white."),
            'Each icon is a metaphor for a video game design tag. Icons in reading order (left to right, top to bottom):',
            items,
            '```',
            '',
        ]
    (DATA / 'PROMPTS.md').write_text('\n'.join(out), encoding='utf-8')


if __name__ == '__main__':
    command = sys.argv[1] if len(sys.argv) > 1 else 'kotlin'
    if command == 'kotlin':
        write_kotlin()
    elif command == 'sheets':
        write_sheets(sys.argv[2])
        write_prompts()
    elif command == 'prompts':
        write_prompts()
    else:
        sys.exit(f'unknown command {command}')
